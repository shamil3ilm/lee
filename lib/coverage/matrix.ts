import { WATCH_EMPLOYERS } from '@/lib/defaults/watch-employers'
import { SEED_COMPANIES } from '@/lib/company-discovery/seed'
import { AUTO_DIRECTORIES } from '@/lib/company-discovery/sources/registry'
import { BROWSE_DIRECTORIES } from '@/lib/company-discovery/sources/browse'
import { isWithin } from '@/lib/regions/tree'
import { catalogBoardsFor } from './compute'
import { PLAYBOOKS } from './playbooks'
import { alertPresets } from './presets'
import type { RegionPlaybook } from './playbook-types'
import { reachFor, sourceReach } from './source-reach'

/**
 * The coverage matrix (docs/job-sources.md › Coverage matrix): per region,
 * which shipped sources can yield its jobs and companies. Generated by
 * scripts/coverage-matrix.ts from the same data the app reads, so it stays
 * current. Pure.
 */

export interface MatrixRow {
  id: string
  label: string
  /** Catalog employer boards for the region: switched on by default / off. */
  boardsOn: number
  boardsOff: number
  /** Broad and park source kinds that reach it. */
  kinds: string[]
  /** Of those, kinds made for this region (a park, a remote board). */
  regionKinds: number
  /** Alert-email sites with a ready search link. */
  alertSites: number
  /** Employers watched by hand (no allowed feed). */
  watchOnly: number
  /** Browse-only job boards. */
  browseBoards: number
  /** Company sources: automatic directories, seed companies, browse-only directories. */
  companyDirectories: string[]
  seedCompanies: number
  browseDirectories: number
  /** Synthetic fixture postings for the region kept by the relevance gate (filled by the script). */
  fixtureKept?: string
}

/** Every source kind the matrix considers for reach (broad, parks, set-up). */
const KINDS = [
  'himalayas', 'remoteok', 'weworkremotely', 'remotive', 'workingnomads', 'jobicy', 'hn_whoishiring', 'adzuna',
  'technopark', 'infopark', 'cyberpark', 'ul_cyberpark', 'ksum', 'email_alert', 'google_alerts', 'linkedin_post',
] as const

function inCovers(ids: readonly string[], covers: readonly string[]): boolean {
  return ids.some((id) => covers.some((c) => isWithin(id, c) || isWithin(c, id)))
}

export function matrixRow(p: RegionPlaybook): MatrixRow {
  const boards = catalogBoardsFor(p)
  const kinds = KINDS.filter((k) => {
    const r = reachFor(sourceReach(k, {}), p.covers)
    return r === 'region' || r === 'broad'
  })
  const group = p.directoryGroup
  return {
    id: p.id,
    label: p.label,
    boardsOn: boards.filter((d) => d.enabled).length,
    boardsOff: boards.filter((d) => !d.enabled).length,
    kinds: [...kinds],
    // Park kinds that ship as catalog boards are counted once, as boards.
    regionKinds: kinds.filter((k) => reachFor(sourceReach(k, {}), p.covers) === 'region' && !boards.some((d) => d.kind === k)).length,
    alertSites: alertPresets(p, 'software developer').filter((a) => a.parsed).length,
    watchOnly: WATCH_EMPLOYERS.filter((e) => p.covers.includes(e.country.toLowerCase()) && e.sourceKey.startsWith('watch:')).length,
    browseBoards: p.boards.length,
    companyDirectories: AUTO_DIRECTORIES.filter((d) => d.places.some((pl) => p.covers.some((c) => isWithin(pl, c) || isWithin(c, pl)))).map((d) => d.label),
    seedCompanies: SEED_COMPANIES.filter((s) => inCovers(s.regionIds, p.covers)).length,
    browseDirectories: group ? BROWSE_DIRECTORIES.filter((d) => d.region === group).length : 0,
  }
}

export function coverageMatrix(): MatrixRow[] {
  return PLAYBOOKS.map(matrixRow)
}

/** Green / amber / red for the matrix, from what ships by default. */
export function matrixStatus(r: MatrixRow): 'green' | 'amber' | 'red' {
  const regionAuto = r.boardsOn + r.regionKinds
  if (regionAuto === 0 && r.boardsOff === 0) return 'red'
  return regionAuto >= 3 ? 'green' : 'amber'
}

export function matrixMarkdown(rows: readonly MatrixRow[]): string {
  const head =
    '| Region | Status | Employer boards (on / off) | Broad & park sources | Alert links | Watched by hand | Browse boards | Company directories (auto) | Seed companies | Browse directories | Fixture postings kept |'
  const sep = '|---|---|---|---|---|---|---|---|---|---|---|'
  const lines = rows.map((r) => {
    const s = matrixStatus(r)
    return `| ${r.label} | ${s} | ${r.boardsOn} / ${r.boardsOff} | ${r.kinds.join(', ') || '—'} | ${r.alertSites} | ${r.watchOnly} | ${r.browseBoards} | ${r.companyDirectories.join(', ') || '—'} | ${r.seedCompanies} | ${r.browseDirectories} | ${r.fixtureKept ?? '—'} |`
  })
  return [head, sep, ...lines].join('\n')
}
